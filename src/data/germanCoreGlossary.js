export function buildCoreGlossaryMap(phoneticGenerator) {
  const map = {};
  for (const [word, partOfSpeech, arabicMeaning, article, plural, ipa] of RAW_CORE_ENTRIES) {
    const key = word.toLowerCase();
    if (map[key]) continue;
    const entry = {
      word,
      lemma: word,
      partOfSpeech,
      contextMeaningArabic: arabicMeaning,
      pronunciationArabic: typeof phoneticGenerator === 'function' ? phoneticGenerator(word) : '',
      ipa: ipa || `[${key}]`,
      exampleGerman: '',
      exampleArabic: '',
    };
    if (article) {
      entry.nounInfo = {
        article,
        singular: `${article} ${word}`,
        plural: plural || '—',
      };
    } else if (partOfSpeech === 'Verb' && /(en|eln|ern|tun|sein)$/i.test(word)) {
      const stem = word.replace(/(en|eln|ern)$/i, '');
      entry.verbInfo = {
        infinitiv: word,
        praesens: `${stem}t`,
        praeteritum: `${stem}te`,
        perfekt: `hat ge${stem}t`,
        auxiliary: 'haben',
        isSeparable: false,
      };
    }
    map[key] = entry;
  }
  return map;
}
